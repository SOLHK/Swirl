//! Exact-record TLS input keeps the first ServerHello gate ahead of rustls and
//! avoids reading past a record into bytes a future Vision owner must retain.
use super::{ClientParameters, backend, hello};
use std::io::{self, Cursor, Read, Write};
use tokio_rustls::rustls::{CipherSuite, ClientConnection, NamedGroup};

const MAX_PLAINTEXT_RECORD: usize = 16 * 1024;
const MAX_CIPHERTEXT_RECORD: usize = MAX_PLAINTEXT_RECORD + 256;
const MAX_FIRST_FLIGHT_RECORDS: usize = 64;
const MAX_HANDSHAKE_RECORDS: usize = 128;
const MAX_HANDSHAKE_BYTES: usize = 256 * 1024;

/// A TLS 1.3 record engine using REALITY's authenticated ClientHello and server
/// certificate. It performs no DNS or socket I/O by itself and never substitutes
/// ordinary TLS on failure. The caller owns the transport, timeout and cancellation.
///
/// This profile uses rustls's native ClientHello with real hybrid/X25519 shares;
/// it does not implement Chrome/uTLS fingerprinting, VLESS or Vision. The async
/// [`super::Stream`] drives this exact engine in the production transport path.
/// Application writes are refused until CertificateVerify and Finished succeed.
pub struct TlsClient {
    connection: ClientConnection,
    first_flight: Cursor<Vec<u8>>,
    first_server_hello: Option<FirstServerHello>,
    record: Vec<u8>,
    filled: usize,
    handshake_records: usize,
    handshake_bytes: usize,
    failed: bool,
    transport_eof: bool,
    peer_closed: bool,
    sent_close: bool,
}

impl std::fmt::Debug for TlsClient {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("TlsClient")
            .field("handshaking", &self.connection.is_handshaking())
            .field("failed", &self.failed)
            .field("peer_closed", &self.peer_closed)
            .finish_non_exhaustive()
    }
}

impl TlsClient {
    /// Prepare exactly one fresh attempt. `unix_time` is the caller's current
    /// Unix timestamp, not a reusable nonce. Every call generates new key material
    /// and random bytes. ALPN is advertised exactly, with bounded nonempty values.
    pub fn new(
        parameters: &ClientParameters,
        unix_time: u32,
        alpn: &[Vec<u8>],
    ) -> Result<Self, &'static str> {
        let prepared = backend::prepare(parameters, unix_time, alpn)?;
        Ok(Self {
            connection: prepared.connection,
            first_flight: Cursor::new(prepared.first_flight),
            first_server_hello: Some(FirstServerHello {
                client_hello: prepared.client_hello,
                offer: prepared.offer,
                handshake: Vec::new(),
                records: Vec::new(),
                count: 0,
                saw_ccs: false,
            }),
            record: vec![0; 5],
            filled: 0,
            handshake_records: 0,
            handshake_bytes: 0,
            failed: false,
            transport_eof: false,
            peer_closed: false,
            sent_close: false,
        })
    }

    pub fn is_handshaking(&self) -> bool {
        self.connection.is_handshaking()
    }

    pub fn wants_write(&self) -> bool {
        !self.failed && (self.first_flight_remaining() || self.connection.wants_write())
    }

    pub fn wants_read(&self) -> bool {
        !self.failed
            && !self.transport_eof
            && !self.first_flight_remaining()
            && self.connection.wants_read()
    }

    pub fn peer_has_closed(&self) -> bool {
        self.peer_closed
    }

    /// Available only after the actual TLS Finished has authenticated the session.
    pub fn negotiated_cipher_suite(&self) -> Option<CipherSuite> {
        if !self.ready() {
            return None;
        }
        self.connection
            .negotiated_cipher_suite()
            .map(|suite| suite.suite())
    }

    pub fn negotiated_group(&self) -> Option<NamedGroup> {
        if !self.ready() {
            return None;
        }
        self.connection
            .negotiated_key_exchange_group()
            .map(|group| group.name())
    }

    pub fn alpn_protocol(&self) -> Option<&[u8]> {
        self.ready().then(|| self.connection.alpn_protocol())?
    }

    /// Writes only the finalized ClientHello and records generated by that exact
    /// rustls connection. Partial writes retain their offset; no re-encoding or
    /// on-socket SessionID patch is possible through this API. A zero write with
    /// pending data, or a non-retryable transport error, ends this attempt.
    pub fn write_tls(&mut self, writer: &mut dyn Write) -> io::Result<usize> {
        self.check_live()?;
        let pending = self.wants_write();
        let result = if self.first_flight_remaining() {
            let position = self.first_flight.position() as usize;
            let result = writer.write(&self.first_flight.get_ref()[position..]);
            if let Ok(written) = result {
                self.first_flight.set_position((position + written) as u64);
            }
            result
        } else {
            self.connection.write_tls(writer)
        };
        let written = self.io_result(result)?;
        if written == 0 && pending {
            self.failed = true;
            return Err(io::Error::new(
                io::ErrorKind::WriteZero,
                "RealityTlsWriteNoProgress",
            ));
        }
        Ok(written)
    }

    /// Read a bounded portion of ONE TLS record and process it only when complete.
    /// Never overreads the next record. Call again after partial reads, drain
    /// `wants_write()`, and read available plaintext before requesting more input.
    /// `WouldBlock` and `Interrupted` preserve all offsets. Other transport errors
    /// end the attempt. A zero read represents transport EOF.
    pub fn read_tls(&mut self, reader: &mut dyn Read) -> io::Result<usize> {
        self.check_live()?;
        if self.peer_closed || self.transport_eof {
            return Ok(0);
        }
        if !self.wants_read() {
            return Err(io::ErrorKind::WouldBlock.into());
        }
        let result = reader.read(&mut self.record[self.filled..]);
        let read = self.io_result(result)?;
        if read == 0 {
            if self.filled != 0 || self.is_handshaking() {
                self.failed = true;
                return Err(io::Error::new(
                    io::ErrorKind::UnexpectedEof,
                    "RealityTruncatedTlsRecordOrHandshake",
                ));
            }
            self.transport_eof = true;
            // Let rustls distinguish authenticated close_notify from unclean
            // EOF, after any already authenticated plaintext has been drained.
            return self.connection.read_tls(&mut io::empty());
        }
        self.filled += read;
        if self.filled == 5 {
            let length = usize::from(u16::from_be_bytes([self.record[3], self.record[4]]));
            if let Err(error) = validate_header(&self.record, length) {
                self.failed = true;
                return Err(invalid(error));
            }
            self.record.resize(5 + length, 0);
        }
        if self.filled == self.record.len() {
            let mut record = std::mem::take(&mut self.record);
            let result = self.process_record(&record);
            record.truncate(5);
            self.record = record;
            self.filled = 0;
            if let Err(error) = result {
                self.failed = true;
                return Err(error);
            }
        }
        Ok(read)
    }

    pub fn read_plaintext(&mut self, plaintext: &mut [u8]) -> io::Result<usize> {
        self.check_live()?;
        if self.is_handshaking() {
            return Err(io::ErrorKind::WouldBlock.into());
        }
        let result = self.connection.reader().read(plaintext);
        self.io_result(result)
    }

    pub fn write_plaintext(&mut self, plaintext: &[u8]) -> io::Result<usize> {
        self.check_live()?;
        if self.sent_close {
            return Err(io::ErrorKind::BrokenPipe.into());
        }
        if !self.ready() {
            return Err(io::ErrorKind::WouldBlock.into());
        }
        let result = self.connection.writer().write(plaintext);
        self.io_result(result)
    }

    /// Close the send direction after authentication. Reverse traffic remains
    /// readable until the peer's close_notify. Cancellation during a handshake
    /// should drop the attempt rather than sending unauthenticated application data.
    pub fn send_close_notify(&mut self) -> io::Result<()> {
        self.check_live()?;
        if !self.ready() {
            return Err(io::ErrorKind::WouldBlock.into());
        }
        if !self.sent_close {
            self.connection.send_close_notify();
            self.sent_close = true;
        }
        Ok(())
    }

    /// Used only by the owning async adapter after an authenticated higher-layer
    /// Direct command. No socket read is performed and no ciphertext is skipped.
    /// Exact-record input means there is no raw read-ahead outside this boundary.
    pub(super) fn take_plaintext_for_raw(&mut self) -> io::Result<Vec<u8>> {
        self.check_live()?;
        if !self.ready() || self.filled != 0 || self.peer_closed || self.transport_eof {
            return Err(invalid("RealityRawReadBoundary"));
        }
        let mut plaintext = Vec::new();
        let mut part = [0; MAX_PLAINTEXT_RECORD];
        loop {
            match self.read_plaintext(&mut part) {
                Ok(0) => return Err(invalid("RealityRawReadClosed")),
                Ok(count) => {
                    if plaintext.len() + count > 64 * 1024 {
                        self.failed = true;
                        return Err(invalid("RealityRawReadBufferLimit"));
                    }
                    plaintext.extend_from_slice(&part[..count]);
                }
                Err(error) if error.kind() == io::ErrorKind::WouldBlock => {
                    return Ok(plaintext);
                }
                Err(error) => return Err(error),
            }
        }
    }

    fn ready(&self) -> bool {
        !self.failed && !self.first_flight_remaining() && !self.is_handshaking()
    }

    fn check_live(&self) -> io::Result<()> {
        if self.failed {
            Err(invalid("RealityConnectionFailed"))
        } else {
            Ok(())
        }
    }

    fn io_result(&mut self, result: io::Result<usize>) -> io::Result<usize> {
        if let Err(error) = &result
            && !matches!(
                error.kind(),
                io::ErrorKind::WouldBlock | io::ErrorKind::Interrupted
            )
        {
            self.failed = true;
        }
        result
    }

    fn first_flight_remaining(&self) -> bool {
        self.first_flight.position() < self.first_flight.get_ref().len() as u64
    }

    fn process_record(&mut self, record: &[u8]) -> io::Result<()> {
        if self.is_handshaking() {
            self.handshake_records += 1;
            self.handshake_bytes += record.len();
            if self.handshake_records > MAX_HANDSHAKE_RECORDS
                || self.handshake_bytes > MAX_HANDSHAKE_BYTES
            {
                return Err(invalid("RealityHandshakeInputLimit"));
            }
        }
        if let Some(first) = &mut self.first_server_hello {
            if !first.push(record).map_err(invalid)? {
                return Ok(());
            }
            let first = self.first_server_hello.take().expect("checked above");
            // Validation finishes BEFORE rustls can consume the actual key owner.
            for record in first.records {
                self.process_verified_record(&record)?;
            }
            Ok(())
        } else {
            self.process_verified_record(record)
        }
    }

    fn process_verified_record(&mut self, record: &[u8]) -> io::Result<()> {
        let mut source = Cursor::new(record);
        // rustls grows its deframer in chunks. Even a complete 16 KiB record
        // may need several read/process calls; each call must make progress.
        for _ in 0..16 {
            if source.position() == record.len() as u64 {
                return Ok(());
            }
            if self.connection.read_tls(&mut source)? == 0 {
                return Err(invalid("RealityTlsRecordNotConsumed"));
            }
            let state = self
                .connection
                .process_new_packets()
                .map_err(|error| io::Error::new(io::ErrorKind::InvalidData, error))?;
            self.peer_closed = state.peer_has_closed();
        }
        if source.position() == record.len() as u64 {
            Ok(())
        } else {
            Err(invalid("RealityTlsRecordNotConsumed"))
        }
    }
}

fn invalid(reason: &'static str) -> io::Error {
    io::Error::new(io::ErrorKind::InvalidData, reason)
}

fn validate_header(header: &[u8], length: usize) -> Result<(), &'static str> {
    if header[1..3] != [3, 3] {
        return Err("RealityTlsRecordVersion");
    }
    let valid = match header[0] {
        20 => length == 1,
        21 => length == 2,
        22 => (1..=MAX_PLAINTEXT_RECORD).contains(&length),
        23 => (1..=MAX_CIPHERTEXT_RECORD).contains(&length),
        _ => false,
    };
    if valid {
        Ok(())
    } else {
        Err("RealityTlsRecordLengthOrType")
    }
}

struct FirstServerHello {
    client_hello: Vec<u8>,
    offer: hello::ClientOffer,
    handshake: Vec<u8>,
    records: Vec<Vec<u8>>,
    count: usize,
    saw_ccs: bool,
}

impl FirstServerHello {
    fn push(&mut self, record: &[u8]) -> Result<bool, &'static str> {
        self.count += 1;
        if self.count > MAX_FIRST_FLIGHT_RECORDS {
            return Err("RealityFirstFlightRecordLimit");
        }
        match record[0] {
            20 if record[5..] == [1] && !self.saw_ccs => self.saw_ccs = true,
            21 => return Err("RealityPeerHandshakeAlert"),
            22 => {
                if self.handshake.len() + record.len() - 5 > MAX_PLAINTEXT_RECORD {
                    return Err("RealityHelloLength");
                }
                self.handshake.extend_from_slice(&record[5..]);
            }
            _ => return Err("RealityFirstFlightRecord"),
        }
        self.records.push(record.to_vec());
        if self.handshake.len() < 4 {
            return Ok(false);
        }
        if self.handshake[0] != 2 {
            return Err("RealityHelloType");
        }
        let length =
            u32::from_be_bytes([0, self.handshake[1], self.handshake[2], self.handshake[3]])
                as usize;
        if length + 4 > MAX_PLAINTEXT_RECORD {
            return Err("RealityHelloLength");
        }
        if self.handshake.len() < length + 4 {
            return Ok(false);
        }
        // `server` rejects extra bytes too: plaintext following ServerHello is
        // never reinterpreted as encrypted or authenticated application data.
        hello::server(&self.handshake, &self.client_hello, &self.offer)?;
        Ok(true)
    }
}

